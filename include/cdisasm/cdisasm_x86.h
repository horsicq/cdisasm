/**
 * One structured operand in Intel display order.
 *
 * size is measured in bytes, or is CDISASM_X86_OPERAND_SIZE_VARIABLE when an
 * architectural run-time configuration determines the size. For memory
 * operands, imm is the signed displacement bit pattern, scale is zero when
 * there is no index register,
 * and address is meaningful only with CDISASM_OPERAND_FLAG_HAS_ADDRESS. For
 * ordinary immediate operands imm is the semantic value. A PC-relative
 * immediate stores the resolved target in imm and its signed displacement in
 * address. reg, base_reg, index_reg, and segment_reg use the
 * CDISASM_X86_REG_* definitions. access records data flow and broadcast is a
 * literal 1-to-N element count. Unused fields and unused operand records are
 * zero.
 */
typedef struct cdisasm_opcode {
    uint8_t type;
    uint8_t size;
    uint8_t scale;
    uint8_t flags;
    cdisasm_x86_reg_id reg;
    cdisasm_x86_reg_id base_reg;
    cdisasm_x86_reg_id index_reg;
    cdisasm_x86_reg_id segment_reg;
    cdisasm_operand_access access;
    cdisasm_x86_broadcast broadcast;
    /** Reserved for ABI evolution; always zero. */
    uint8_t reserved[2];
    uint64_t address;
    uint64_t imm;
} cdisasm_opcode;
typedef cdisasm_opcode cdisasm_x86_operand;

/**
 * Byte offsets for the effective x86 encoding.
 *
 * Every offset is relative to the first instruction byte. An absent ModRM,
 * SIB, displacement, immediate, or opcode-selector byte has a zero size/count
 * and its corresponding offset/value fields are zero. selector_offset is the
 * trailing selector byte used by the 0F 0F 3DNow encoding and exact XOP
 * SE_IMM8 forms such as VPBLENDVB, VPCMOV, and VPPERM; that byte is encoding
 * metadata, not an immediate operand.
 */
typedef struct cdisasm_x86_encoding {
    uint8_t prefix_size;
    uint8_t opcode_offset;
    uint8_t opcode_size;
    uint8_t modrm_offset;
    uint8_t modrm;
    uint8_t sib_offset;
    uint8_t sib;
    uint8_t displacement_offset;
    uint8_t displacement_size;
    uint8_t immediate_count;
    uint8_t immediate_offset[2];
    uint8_t immediate_size[2];
    uint8_t selector_offset;
    /** Reserved for ABI evolution; always zero. */
    uint8_t reserved;
} cdisasm_x86_encoding;

/** Compact structured result produced by cdisasm_decode. */
