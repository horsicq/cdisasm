/** Returns nonzero when instruction has the requested x86 ISA-family group. */
static inline int cdisasm_instruction_has_x86_group(
    const cdisasm_instruction *instruction,
    cdisasm_x86_group_id group_id)
{
    uint8_t index;

    if (instruction == NULL
        || instruction->x86_group_count > CDISASM_MAX_X86_GROUPS
        || group_id < CDISASM_X86_GROUP_FIRST
        || group_id > CDISASM_X86_GROUP_LAST) {
        return 0;
    }
    for (index = 0; index < instruction->x86_group_count; ++index) {
        if (instruction->x86_group_ids[index] == group_id) {
            return 1;
        }
        if (instruction->x86_group_ids[index] > group_id) {
            break;
        }
    }
    return 0;
}

