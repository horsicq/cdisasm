/**
 * APX default-flags value (DFV) encoded by CCMP/CTEST forms.
 *
 * The low four bits describe the flags supplied when the conditional
 * compare does not write the architectural status flags.  They are kept as
 * a compact value so callers can inspect the encoding without parsing the
 * formatted decorator.
 */
typedef uint8_t cdisasm_x86_default_flags;
enum {
    CDISASM_X86_DEFAULT_FLAGS_NONE = 0,
    CDISASM_X86_DEFAULT_FLAG_CF = UINT8_C(1) << 0,
    CDISASM_X86_DEFAULT_FLAG_ZF = UINT8_C(1) << 1,
    CDISASM_X86_DEFAULT_FLAG_SF = UINT8_C(1) << 2,
    CDISASM_X86_DEFAULT_FLAG_OF = UINT8_C(1) << 3
};

