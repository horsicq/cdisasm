#!/usr/bin/env python3
"""Generate conservative x86/Arm opcode-coverage manifests for cdisasm.

The generator deliberately exposes several confidence levels.  A mnemonic in
the public ID catalog is not treated as an implemented encoding.  A mnemonic
referenced by decoder source is still not exact form evidence.  Exact form
evidence comes from a successful checked-in byte corpus row mapped through XED
or the AARCHMRS decode tree.  Conversely, a checked-in
UNSUPPORTED_INSTRUCTION row is called a verified missing encoding only when an
upstream source recognizes the complete bytes as an allocated form.

Only Python's standard library is required.  The reports generated by this
script are not compiled into cdisasm; runtime tables are generated separately
under tools/isa_codegen.
"""

from __future__ import annotations

import argparse
import concurrent.futures
import csv
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
from typing import Any, Iterable, Iterator


GENERATOR_VERSION = 5
MANIFEST_SCHEMA_VERSION = 2

# Public cdisasm_arm_decode_option bit used by tests/data/arm_opcodes.tsv.
# Keep corpus byte transport separate from the canonical instruction word:
# A32/A64 reverse the complete word, while T32 reverses each halfword.
ARM_DECODE_OPTION_BIG_ENDIAN = 1 << 0

NAME_DEFINE_RE = re.compile(
    r"^#define\s+CDISASM_(X86|ARM)_NAME_([A-Z0-9_]+)\s+UINT16_C\((\d+)\)",
    re.MULTILINE,
)
NAME_REFERENCE_RE = re.compile(r"CDISASM_(X86|ARM)_NAME_([A-Z0-9_]+)")
XED_TABLE_RE = re.compile(
    r"^\s*\d+\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s+(\S+)\s+"
    r"ATTRIBUTES:\s*(.*)$"
)


class CoverageError(RuntimeError):
    """A reproducibility or input-format failure."""


def read_json(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as stream:
        value = json.load(stream)
    if not isinstance(value, dict):
        raise CoverageError(f"expected a JSON object in {path}")
    return value


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        while True:
            block = stream.read(1024 * 1024)
            if not block:
                break
            digest.update(block)
    return digest.hexdigest()


def stable_digest(value: Any) -> str:
    encoded = json.dumps(
        value, ensure_ascii=True, sort_keys=True, separators=(",", ":")
    ).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def git_value(repository: Path, *arguments: str) -> str | None:
    try:
        process = subprocess.run(
            ["git", "-C", str(repository), *arguments],
            check=False,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            encoding="utf-8",
        )
    except OSError:
        return None
    if process.returncode != 0:
        return None
    return process.stdout.strip()


def verify_git_baseline(
    repository: Path,
    expected_commit: str,
    label: str,
    allow_source_drift: bool,
) -> str | None:
    actual = git_value(repository, "rev-parse", "HEAD")
    if actual != expected_commit and not allow_source_drift:
        actual_text = actual if actual is not None else "not a Git checkout"
        raise CoverageError(
            f"{label} baseline mismatch: expected {expected_commit}, got "
            f"{actual_text}; use --allow-source-drift only for exploratory output"
        )
    return actual


def parse_name_ids(path: Path, architecture: str) -> tuple[dict[str, int], dict[int, str]]:
    text = path.read_text(encoding="utf-8")
    names: dict[str, int] = {}
    ids: dict[int, str] = {}
    for match in NAME_DEFINE_RE.finditer(text):
        if match.group(1) != architecture:
            continue
        name = match.group(2)
        value = int(match.group(3))
        if name in ("NONE", "COUNT"):
            continue
        names[name] = value
        ids.setdefault(value, name)
    if not names:
        raise CoverageError(f"no {architecture} name IDs found in {path}")
    return names, ids


def merge_name_catalogs(
    catalogs: Iterable[tuple[dict[str, int], dict[int, str]]]
) -> tuple[dict[str, int], dict[int, str]]:
    names: dict[str, int] = {}
    ids: dict[int, str] = {}
    for source_names, source_ids in catalogs:
        for name, value in source_names.items():
            if name in names and names[name] != value:
                raise CoverageError(
                    f"conflicting name ID for {name}: {names[name]} and {value}"
                )
            if value in ids and ids[value] != name:
                raise CoverageError(
                    f"name ID {value} is shared by {ids[value]} and {name}"
                )
            names[name] = value
            ids[value] = name
        for value, name in source_ids.items():
            if value in ids and ids[value] != name:
                raise CoverageError(
                    f"name ID {value} is shared by {ids[value]} and {name}"
                )
    return names, ids


def read_iform_inventory(path: Path) -> set[str]:
    with path.open("r", encoding="utf-8", newline="") as stream:
        rows = list(csv.DictReader(stream, dialect="excel-tab"))
    result = {str(row.get("iform", "")) for row in rows}
    if not result or "" in result or len(result) != len(rows):
        raise CoverageError(f"invalid or duplicate IFORM inventory in {path}")
    return result


def parse_decoder_name_references(
    paths: Iterable[Path], architecture: str
) -> set[str]:
    result: set[str] = set()
    for path in paths:
        text = path.read_text(encoding="utf-8")
        for match in NAME_REFERENCE_RE.finditer(text):
            if match.group(1) == architecture and match.group(2) not in ("NONE", "COUNT"):
                result.add(match.group(2))
    return result


def corpus_rows(path: Path, architecture: str) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    with path.open("r", encoding="utf-8", newline="") as stream:
        for line_number, raw_line in enumerate(stream, 1):
            line = raw_line.rstrip("\r\n")
            if not line or line.startswith("#"):
                continue
            fields = line.split("\t")
            minimum = 9 if architecture == "X86" else 14
            if len(fields) < minimum:
                raise CoverageError(
                    f"{path}:{line_number}: expected at least {minimum} tab fields"
                )
            if architecture == "X86":
                encoded = b"" if fields[8] == "-" else bytes.fromhex(fields[8])
                row = {
                    "case": fields[0],
                    "cpu_id": fields[1],
                    "mode": int(fields[2], 0),
                    "status": fields[4],
                    "decoded_size": int(fields[5], 0),
                    "bytes": encoded,
                    "line": line_number,
                }
            else:
                encoded = b"" if fields[13] == "-" else bytes.fromhex(fields[13])
                row = {
                    "case": fields[0],
                    "cpu_id": fields[1],
                    "mode": int(fields[2], 0),
                    "flags": int(fields[4], 0),
                    "status": fields[5],
                    "decoded_size": int(fields[6], 0),
                    "name_id": int(fields[7], 0),
                    "bytes": encoded,
                    "line": line_number,
                }
            rows.append(row)
    return rows


def find_executable(explicit: Path | None, kit: Path, stem: str) -> Path:
    if explicit is not None:
        if not explicit.is_file():
            raise CoverageError(f"executable not found: {explicit}")
        return explicit
    candidates = [kit / "bin" / stem, kit / "bin" / f"{stem}.exe"]
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    raise CoverageError(f"could not find {stem} below {kit / 'bin'}")


def find_xed_kit(xed_root: Path, explicit: Path | None) -> Path:
    if explicit is not None:
        return explicit
    candidates = sorted(
        path.parent.parent
        for path in xed_root.glob("obj*/wkit/bin/xed-tables*")
        if path.is_file() and path.name in ("xed-tables", "xed-tables.exe")
    )
    if not candidates:
        raise CoverageError(
            "no XED wkit found; pass --xed-kit pointing to a built wkit directory"
        )
    return candidates[0]


def xed_form_inventory(xed_tables: Path) -> list[dict[str, Any]]:
    process = subprocess.Popen(
        [str(xed_tables)],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    assert process.stdout is not None
    forms: dict[str, dict[str, Any]] = {}
    for line in process.stdout:
        match = XED_TABLE_RE.match(line.rstrip("\r\n"))
        if match is None:
            continue
        iclass, iform, category, extension, isa_set, attributes = match.groups()
        record = {
            "iform": iform,
            "iclass": iclass,
            "category": category,
            "extension": extension,
            "isa_set": isa_set,
            "attributes": " ".join(sorted(attributes.split())),
            "xed_descriptor_rows": 1,
        }
        old = forms.get(iform)
        if old is not None:
            identity_fields = ("iform", "iclass", "category", "extension", "isa_set")
            if any(old[field] != record[field] for field in identity_fields):
                process.kill()
                raise CoverageError(f"XED emitted inconsistent records for {iform}")
            merged_attributes = set(old["attributes"].split())
            merged_attributes.update(record["attributes"].split())
            old["attributes"] = " ".join(sorted(merged_attributes))
            old["xed_descriptor_rows"] += 1
        else:
            forms[iform] = record
    stderr = process.stderr.read() if process.stderr is not None else ""
    return_code = process.wait()
    if return_code != 0:
        raise CoverageError(
            f"{xed_tables} failed with exit code {return_code}: {stderr.strip()}"
        )
    if not forms:
        raise CoverageError(f"{xed_tables} did not emit any instruction forms")
    return sorted(forms.values(), key=lambda item: item["iform"])


def xed_form_inventory_from_json(
    path: Path,
    expected_version: str,
    expected_sha256: str,
    allow_source_drift: bool,
) -> tuple[list[dict[str, Any]], int]:
    if not path.is_file():
        raise CoverageError(f"XED metadata export not found: {path}")
    actual_sha256 = sha256_file(path)
    if actual_sha256 != expected_sha256 and not allow_source_drift:
        raise CoverageError(
            f"XED metadata export hash mismatch: expected {expected_sha256}, "
            f"got {actual_sha256}"
        )
    document = read_json(path)
    if document.get("Version") != expected_version and not allow_source_drift:
        raise CoverageError(
            f"XED metadata version mismatch: expected {expected_version}, "
            f"got {document.get('Version')!r}"
        )
    records = document.get("Instructions")
    if not isinstance(records, list):
        raise CoverageError(f"XED metadata export has no Instructions list: {path}")
    forms: dict[str, dict[str, Any]] = {}
    for source in records:
        if not isinstance(source, dict):
            raise CoverageError("XED metadata instruction record is not an object")
        iform = str(source.get("iform", ""))
        record = {
            "iform": iform,
            "iclass": str(source.get("iclass", "")),
            "category": str(source.get("category", "")),
            "extension": str(source.get("extension", "")),
            "isa_set": str(source.get("isa_set", "")),
            "attributes": " ".join(sorted(source.get("attributes") or [])),
            "xed_descriptor_rows": 1,
        }
        old = forms.get(iform)
        if old is None:
            forms[iform] = record
            continue
        identity_fields = ("iform", "iclass", "category", "extension", "isa_set")
        if any(old[field] != record[field] for field in identity_fields):
            raise CoverageError(f"XED JSON emitted inconsistent records for {iform}")
        merged_attributes = set(old["attributes"].split())
        merged_attributes.update(record["attributes"].split())
        old["attributes"] = " ".join(sorted(merged_attributes))
        old["xed_descriptor_rows"] += 1
    if not forms:
        raise CoverageError("XED metadata export contains no instruction forms")
    return sorted(forms.values(), key=lambda item: item["iform"]), len(records)


def decode_one_with_xed(
    xed_dec: Path,
    mode: int,
    encoded: bytes,
    profile_options: tuple[str, ...] = (),
) -> dict[str, Any]:
    command = [str(xed_dec)]
    # The pinned xed-dec example selects legacy 32-bit mode by default and
    # only defines explicit -16 and -64 switches.  Passing the nonexistent
    # "-32" option makes it concatenate that text with the byte string and
    # report an odd-nibble parse error instead of decoding the probe.
    if mode in (16, 64):
        command.append(f"-{mode}")
    elif mode != 32:
        return {
            "return_code": -1,
            "decoded": False,
            "diagnostic": f"unsupported XED decode mode {mode}",
        }
    # XED's standalone decoder intentionally defaults MPX and CET off, while
    # the cdisasm corpus contains EXTRA_OK witnesses for those optional
    # instruction families.  Keep the default decode as the primary oracle,
    # and let callers request the profile-specific decode as an additional
    # witness.  Options are restricted to the two explicit XED decoder
    # profile switches so this remains deterministic and auditable.
    for option in profile_options:
        if option not in ("-mpx", "-cet", "-chip", "PENTIUM4"):
            return {
                "return_code": -1,
                "decoded": False,
                "diagnostic": f"unsupported XED profile option {option}",
            }
        command.append(option)
    command.append(encoded.hex())
    process = subprocess.run(
        command,
        check=False,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    output = process.stdout
    fields: dict[str, Any] = {
        "return_code": process.returncode,
        "decoded": False,
    }
    patterns = {
        "iclass": r"(?m)^iclass\s+(\S+)",
        "iform": r"(?m)^iform-enum-name\s+(\S+)",
        "length": r"(?m)^instruction-length\s+(\d+)",
        "isa_set": r"(?m)^ISA SET:\s*\[([^]]+)\]",
    }
    for key, pattern in patterns.items():
        match = re.search(pattern, output)
        if match is not None:
            fields[key] = int(match.group(1)) if key == "length" else match.group(1)
    fields["decoded"] = "iform" in fields and "length" in fields
    if not fields["decoded"]:
        fields["diagnostic"] = " ".join(output.strip().split())[:240]
    return fields


def map_xed_corpus(
    rows: list[dict[str, Any]],
    xed_dec: Path,
    relevant_statuses: set[str],
    jobs: int,
) -> tuple[dict[str, list[dict[str, Any]]], list[dict[str, Any]]]:
    # EXTRA_OK is the corpus status used for opt-in extension witnesses.  In
    # addition to the default XED profile, decode those rows with MPX and CET
    # enabled.  This is necessary for XED's profile-gated legacy encodings
    # (for example BND* and CET shadow-stack instructions), which otherwise
    # decode as their architectural collision such as NOP.
    profile_sets = {(): "default", ("-mpx",): "mpx", ("-cet",): "cet"}

    def profiles_for_row(row: dict[str, Any]) -> tuple[tuple[str, ...], ...]:
        """Return deterministic XED profiles appropriate for one witness.

        UD0 has two architecturally distinct XED forms selected by the
        historical chip profile.  The default all-features profile chooses
        the short PPRO_UD0_SHORT form; a Pentium 4 decode is required to
        witness the long PPRO_UD0_LONG catalog rows.  Keep this profile
        targeted to UD0 so ordinary EXTRA_OK rows retain the default/MPX/CET
        matrix and its bounded process cost.
        """
        encoded = row.get("bytes", b"")
        # The corpus format intentionally does not carry an upstream IFORM,
        # so the old row.get("iform") check could never select the Pentium 4
        # profile.  UD0 has two historical XED forms at the same opcode: the
        # default profile exposes the short PPRO_UD0_SHORT form while a
        # Pentium 4 decode is required for PPRO_UD0_LONG.  Decode both
        # profiles for every complete 0F FF witness and let the IFORM output
        # choose the exact long form.
        if len(encoded) >= 2 and encoded[:2] == b"\x0f\xff":
            return ((), ("-chip", "PENTIUM4"))

        # 0F 18 /4, /6, and /7 were architectural NOP encodings on the old
        # profiles, but modern XED assigns the same bytes to MOVRS and
        # ICACHE_PREFETCH families under its default profile.  A targeted
        # Pentium 4 decode retains exact evidence for the legacy FAT_NOP
        # IFORMs without confusing a modern prefetch witness with NOP.
        if (len(encoded) >= 3 and encoded[:2] == b"\x0f\x18"
                and ((encoded[2] >> 3) & 7) in (4, 6, 7)):
            profiles = list(profile_sets) if row["status"] == "EXTRA_OK" else [()]
            profiles.append(("-chip", "PENTIUM4"))
            return tuple(profiles)

        if row["status"] == "EXTRA_OK":
            return tuple(profile_sets)
        return ((),)

    tasks = {
        (row["mode"], row["bytes"], profile)
        for row in rows
        if row["status"] in relevant_statuses
        and row["mode"] in (16, 32, 64)
        for profile in profiles_for_row(row)
    }
    decoded: dict[tuple[int, bytes, tuple[str, ...]], dict[str, Any]] = {}
    with concurrent.futures.ThreadPoolExecutor(max_workers=max(1, jobs)) as executor:
        futures = {
            executor.submit(decode_one_with_xed, xed_dec, mode, encoded, profile):
            (mode, encoded, profile)
            for mode, encoded, profile in tasks
        }
        for future in concurrent.futures.as_completed(futures):
            decoded[futures[future]] = future.result()

    evidence: dict[str, list[dict[str, Any]]] = {}
    anomalies: list[dict[str, Any]] = []
    for row in rows:
        if row["status"] not in relevant_statuses:
            continue
        profiles = profiles_for_row(row)
        results = [
            decoded.get((row["mode"], row["bytes"], profile))
            for profile in profiles
        ]
        successful_results = [
            result for result in results if result is not None and result.get("decoded")
        ]
        if not successful_results:
            result = next((result for result in results if result is not None), None)
            anomalies.append(
                {
                    "case": row["case"],
                    "line": row["line"],
                    "reason": "upstream_did_not_decode",
                    "diagnostic": (result or {}).get("diagnostic", ""),
                }
            )
            continue
        length_results = [
            result for result in successful_results if result["length"] == len(row["bytes"])
        ]
        if not length_results:
            result = successful_results[0]
            anomalies.append(
                {
                    "case": row["case"],
                    "line": row["line"],
                    "reason": "upstream_length_differs",
                    "upstream_length": result["length"],
                    "corpus_bytes": len(row["bytes"]),
                }
            )
            continue
        for result in length_results:
            evidence.setdefault(result["iform"], []).append(
                {
                    "case": row["case"],
                    "line": row["line"],
                    "status": row["status"],
                    "mode": row["mode"],
                    "bytes": row["bytes"].hex(),
                    "iclass": result.get("iclass", ""),
                }
            )
    return evidence, anomalies


def normalize_xed_name(
    iclass: str,
    catalog: dict[str, int],
    config: dict[str, Any],
) -> tuple[str | None, str, str]:
    if iclass in catalog:
        return iclass, "exact", ""
    explicit = config.get("x86_name_aliases", {}).get(iclass)
    if explicit in catalog:
        return explicit, "explicit_alias", "EXPLICIT_ALIAS"

    for rule in config.get("x86_normalization_rules", []):
        operation = rule.get("operation")
        candidate: str | None = None
        if operation == "strip_suffix" and iclass.endswith(rule["value"]):
            candidate = iclass[: -len(rule["value"])]
        elif operation == "regex_replace":
            candidate = re.sub(rule["pattern"], rule["replacement"], iclass)
            if candidate == iclass:
                candidate = None
        elif operation == "strip_string_prefix":
            for prefix in rule.get("values", []):
                if iclass.startswith(prefix):
                    candidate = iclass[len(prefix):]
                    break
        elif operation == "strip_suffix_if_catalogued":
            for suffix in rule.get("values", []):
                if iclass.endswith(suffix):
                    candidate = iclass[: -len(suffix)]
                    break
        if candidate in catalog:
            return candidate, "normalization_rule", str(rule.get("id", ""))
    return None, "none", ""


def evidence_cases(
    entries: list[dict[str, Any]], statuses: set[str]
) -> list[str]:
    return sorted({entry["case"] for entry in entries if entry["status"] in statuses})


def classify_form(
    entries: list[dict[str, Any]],
    success: set[str],
    missing: set[str],
    profile: set[str],
    source_match: bool,
    catalog_match: bool,
) -> str:
    success_cases = evidence_cases(entries, success)
    missing_cases = evidence_cases(entries, missing)
    if success_cases and missing_cases:
        return "corpus_partial"
    if success_cases:
        return "corpus_reachable"
    if missing_cases:
        return "verified_missing_encoding"
    if evidence_cases(entries, profile):
        return "profile_rejected_probe"
    if source_match:
        return "source_assignment_only"
    if catalog_match:
        return "catalog_only"
    return "unmatched_upstream"


def first_assembly_literal(node: dict[str, Any]) -> str:
    for symbol in (node.get("assembly") or {}).get("symbols", []):
        if symbol.get("_type") == "Instruction.Symbols.Literal":
            return str(symbol.get("value", ""))
    return ""


def assembly_template(node: dict[str, Any]) -> str:
    """Return a compact, prose-free representation of an assembly production."""
    result: list[str] = []
    for symbol in (node.get("assembly") or {}).get("symbols", []):
        symbol_type = symbol.get("_type")
        if symbol_type == "Instruction.Symbols.Literal":
            result.append(str(symbol.get("value", "")))
        elif symbol_type == "Instruction.Symbols.RuleReference":
            result.append(f"<rule:{symbol.get('rule_id', '')}>")
        else:
            result.append(f"<symbol:{symbol_type or 'unknown'}>")
    return "".join(result)


def feature_names(value: Any) -> set[str]:
    result: set[str] = set()
    if isinstance(value, dict):
        if value.get("_type") == "AST.Identifier":
            identifier = value.get("value")
            if isinstance(identifier, str) and identifier.startswith("FEAT_"):
                result.add(identifier)
        for child in value.values():
            result.update(feature_names(child))
    elif isinstance(value, list):
        for child in value:
            result.update(feature_names(child))
    return result


def apply_arm_encoding(
    inherited_mask: int,
    inherited_value: int,
    inherited_width: int | None,
    encoding: dict[str, Any] | None,
) -> tuple[int, int, int | None]:
    if not encoding:
        return inherited_mask, inherited_value, inherited_width
    width_value = encoding.get("width")
    width = int(width_value) if width_value is not None else inherited_width
    if inherited_width is not None and width is not None and width != inherited_width:
        inherited_mask = 0
        inherited_value = 0
    mask = inherited_mask
    value = inherited_value
    for field in encoding.get("values", []):
        bit_range = field.get("range") or {}
        start = int(bit_range.get("start", 0))
        field_width = int(bit_range.get("width", 0))
        raw = str((field.get("value") or {}).get("value", "")).strip("'")
        if len(raw) != field_width or any(bit not in "01x" for bit in raw):
            raise CoverageError(
                f"unsupported Arm encoding value {raw!r} at {start}:{field_width}"
            )
        field_bits = ((1 << field_width) - 1) << start
        mask &= ~field_bits
        value &= ~field_bits
        for offset, bit in enumerate(reversed(raw)):
            bit_number = start + offset
            if bit in "01":
                mask |= 1 << bit_number
                if bit == "1":
                    value |= 1 << bit_number
    if width is not None:
        width_mask = (1 << width) - 1
        mask &= width_mask
        value &= width_mask
    return mask, value, width


def arm_alias_record(node: dict[str, Any]) -> dict[str, Any]:
    return {
        "internal_name": str(node.get("name", "")),
        "mnemonic": first_assembly_literal(node),
        "assembly_template": assembly_template(node),
        "condition_digest": stable_digest(node.get("condition")),
        "operation_id": str(node.get("operation_id", "")),
        "features": sorted(feature_names(node.get("condition"))),
    }


def flatten_arm_forms(document: dict[str, Any]) -> list[dict[str, Any]]:
    forms: list[dict[str, Any]] = []

    def visit(
        node: dict[str, Any],
        instruction_set: str,
        path: tuple[str, ...],
        inherited_mask: int,
        inherited_value: int,
        inherited_width: int | None,
        conditions: tuple[Any, ...],
    ) -> None:
        node_name = str(node.get("name", ""))
        node_path = path + (node_name,)
        mask, value, width = apply_arm_encoding(
            inherited_mask,
            inherited_value,
            inherited_width,
            node.get("encoding"),
        )
        node_conditions = conditions + (node.get("condition"),)
        node_type = node.get("_type")
        if node_type == "Instruction.Instruction":
            if width not in (16, 32):
                raise CoverageError(
                    f"unexpected Arm leaf width {width!r} for {'/'.join(node_path)}"
                )
            aliases = [
                arm_alias_record(child)
                for child in node.get("children", [])
                if child.get("_type") == "Instruction.InstructionAlias"
            ]
            features: set[str] = set()
            for condition in node_conditions:
                features.update(feature_names(condition))
            for alias in aliases:
                features.update(alias["features"])
            forms.append(
                {
                    "form_id": "/".join(node_path),
                    "instruction_set": instruction_set,
                    "internal_name": node_name,
                    "mnemonic": first_assembly_literal(node),
                    "assembly_template": assembly_template(node),
                    "width": width,
                    "fixed_mask": mask,
                    "fixed_value": value,
                    "fixed_bits": mask.bit_count(),
                    "condition_digest": stable_digest(node_conditions),
                    "assertions_digest": stable_digest(node.get("assertions")),
                    "operation_id": str(node.get("operation_id", "")),
                    "features": sorted(features),
                    "aliases": aliases,
                    "source_order": len(forms),
                }
            )
        for child in node.get("children", []):
            if child.get("_type") != "Instruction.InstructionAlias":
                visit(
                    child,
                    instruction_set,
                    node_path,
                    mask,
                    value,
                    width,
                    node_conditions,
                )

    for root in document.get("instructions", []):
        instruction_set = str(root.get("name", ""))
        if instruction_set not in ("A32", "T32", "A64"):
            raise CoverageError(f"unexpected Arm instruction set {instruction_set!r}")
        visit(root, instruction_set, (), 0, 0, None, ())
    if not forms:
        raise CoverageError("AARCHMRS did not contain any canonical instruction leaves")
    return forms


def arm_word(
    mode: int, encoded: bytes, big_endian: bool
) -> tuple[str, int, int] | None:
    byte_order = "big" if big_endian else "little"
    if mode == 1 and len(encoded) == 4:
        return "A32", 32, int.from_bytes(encoded, byte_order)
    if mode == 2 and len(encoded) == 2:
        return "T32", 16, int.from_bytes(encoded, byte_order)
    if mode == 2 and len(encoded) == 4:
        first = int.from_bytes(encoded[:2], byte_order)
        second = int.from_bytes(encoded[2:], byte_order)
        return "T32", 32, (first << 16) | second
    if mode == 3 and len(encoded) == 4:
        return "A64", 32, int.from_bytes(encoded, byte_order)
    return None


def map_arm_corpus(
    rows: list[dict[str, Any]],
    forms: list[dict[str, Any]],
    id_names: dict[int, str],
    relevant_statuses: set[str],
) -> tuple[
    dict[str, list[dict[str, Any]]],
    dict[str, list[dict[str, Any]]],
    list[dict[str, Any]],
]:
    by_shape: dict[tuple[str, int], list[dict[str, Any]]] = {}
    for form in forms:
        by_shape.setdefault((form["instruction_set"], form["width"]), []).append(form)

    evidence: dict[str, list[dict[str, Any]]] = {}
    ambiguous: dict[str, list[dict[str, Any]]] = {}
    anomalies: list[dict[str, Any]] = []
    for row in rows:
        if row["status"] not in relevant_statuses:
            continue
        converted = arm_word(
            row["mode"],
            row["bytes"],
            (row["flags"] & ARM_DECODE_OPTION_BIG_ENDIAN) != 0,
        )
        if converted is None:
            anomalies.append(
                {
                    "case": row["case"],
                    "line": row["line"],
                    "reason": "unsupported_mode_or_byte_width",
                }
            )
            continue
        instruction_set, width, word = converted
        mask_candidates = [
            form
            for form in by_shape.get((instruction_set, width), [])
            if word & form["fixed_mask"] == form["fixed_value"]
        ]
        decoded_name = id_names.get(row["name_id"], "")
        candidates = [
            form
            for form in mask_candidates
            if decoded_name == form["mnemonic"]
            or decoded_name
            in {alias["mnemonic"] for alias in form["aliases"]}
        ]
        if not candidates:
            anomalies.append(
                {
                    "case": row["case"],
                    "line": row["line"],
                    "reason": (
                        "upstream_fixed_mask_name_no_match"
                        if mask_candidates
                        else "upstream_fixed_mask_no_match"
                    ),
                    "instruction_set": instruction_set,
                    "word": f"0x{word:0{width // 4}x}",
                    "cdisasm_name": decoded_name,
                }
            )
            continue
        specificity = max(form["fixed_bits"] for form in candidates)
        best = [form for form in candidates if form["fixed_bits"] == specificity]
        entry = {
            "case": row["case"],
            "line": row["line"],
            "status": row["status"],
            "mode": row["mode"],
            "bytes": row["bytes"].hex(),
            "cdisasm_name_id": row["name_id"],
            "cdisasm_name": id_names.get(row["name_id"], ""),
        }
        if len(best) == 1:
            evidence.setdefault(best[0]["form_id"], []).append(entry)
        else:
            candidate_ids = sorted(form["form_id"] for form in best)
            ambiguous_entry = dict(entry)
            ambiguous_entry["candidate_form_ids"] = candidate_ids
            key = stable_digest(candidate_ids)
            ambiguous.setdefault(key, []).append(ambiguous_entry)
    return evidence, ambiguous, anomalies


def normalize_arm_name(
    form: dict[str, Any], catalog: dict[str, int], config: dict[str, Any]
) -> tuple[str | None, str, str]:
    explicit = config.get("arm_name_aliases", {}).get(form["internal_name"])
    if explicit in catalog:
        return explicit, "explicit_alias", "EXPLICIT_ALIAS"
    mnemonic = form["mnemonic"]
    if mnemonic in catalog:
        return mnemonic, "exact", ""
    alias_matches = sorted(
        {
            alias["mnemonic"]
            for alias in form["aliases"]
            if alias["mnemonic"] in catalog
        }
    )
    if alias_matches:
        return alias_matches[0], "architectural_alias", ",".join(alias_matches)
    return None, "none", ""


def compact_cases(entries: list[dict[str, Any]], statuses: set[str]) -> str:
    return ",".join(evidence_cases(entries, statuses))


def build_x86_rows(
    forms: list[dict[str, Any]],
    evidence: dict[str, list[dict[str, Any]]],
    catalog: dict[str, int],
    source_names: set[str],
    generated_iforms: set[str],
    config: dict[str, Any],
) -> list[dict[str, Any]]:
    policy = config["status_policy"]
    success = set(policy["successful_corpus_statuses"])
    missing = set(policy["missing_encoding_statuses"])
    profile = set(policy["profile_only_statuses"])
    result: list[dict[str, Any]] = []
    for form in forms:
        name, match_kind, match_rule = normalize_xed_name(
            form["iclass"], catalog, config
        )
        entries = evidence.get(form["iform"], [])
        source_match = name in source_names if name is not None else False
        status = classify_form(
            entries, success, missing, profile, source_match, name is not None
        )
        result.append(
            {
                **form,
                "coverage_status": status,
                "cdisasm_name": name or "",
                "cdisasm_name_id": catalog.get(name, 0) if name else 0,
                "name_match_kind": match_kind,
                "name_match_rule": match_rule,
                "source_name_reference": source_match,
                "generated_fallback_assignment": form["iform"] in generated_iforms,
                "success_cases": compact_cases(entries, success),
                "missing_cases": compact_cases(entries, missing),
                "profile_cases": compact_cases(entries, profile),
            }
        )
    return result


def build_arm_rows(
    forms: list[dict[str, Any]],
    evidence: dict[str, list[dict[str, Any]]],
    catalog: dict[str, int],
    source_names: set[str],
    config: dict[str, Any],
) -> list[dict[str, Any]]:
    policy = config["status_policy"]
    success = set(policy["successful_corpus_statuses"])
    missing = set(policy["missing_encoding_statuses"])
    profile = set(policy["profile_only_statuses"])
    result: list[dict[str, Any]] = []
    for form in forms:
        name, match_kind, match_rule = normalize_arm_name(
            form, catalog, config
        )
        entries = evidence.get(form["form_id"], [])
        source_match = name in source_names if name is not None else False
        status = classify_form(
            entries, success, missing, profile, source_match, name is not None
        )
        width_digits = form["width"] // 4
        result.append(
            {
                "form_id": form["form_id"],
                "instruction_set": form["instruction_set"],
                "internal_name": form["internal_name"],
                "mnemonic": form["mnemonic"],
                "alias_mnemonics": ",".join(
                    sorted({alias["mnemonic"] for alias in form["aliases"]})
                ),
                "assembly_template": form["assembly_template"],
                "width": form["width"],
                "fixed_mask": f"0x{form['fixed_mask']:0{width_digits}x}",
                "fixed_value": f"0x{form['fixed_value']:0{width_digits}x}",
                "fixed_bits": form["fixed_bits"],
                "features": ",".join(form["features"]),
                "operation_id": form["operation_id"],
                "condition_digest": form["condition_digest"],
                "assertions_digest": form["assertions_digest"],
                "coverage_status": status,
                "cdisasm_name": name or "",
                "cdisasm_name_id": catalog.get(name, 0) if name else 0,
                "name_match_kind": match_kind,
                "name_match_rule": match_rule,
                "source_name_reference": source_match,
                "success_cases": compact_cases(entries, success),
                "missing_cases": compact_cases(entries, missing),
                "profile_cases": compact_cases(entries, profile),
            }
        )
    return result


def counter_by(rows: list[dict[str, Any]], key: str) -> dict[str, int]:
    counts: dict[str, int] = {}
    for row in rows:
        value = str(row.get(key, ""))
        counts[value] = counts.get(value, 0) + 1
    return dict(sorted(counts.items()))


def top_unmatched(
    rows: list[dict[str, Any]], key: str, limit: int = 25
) -> list[dict[str, Any]]:
    counts: dict[str, int] = {}
    for row in rows:
        if row["coverage_status"] != "unmatched_upstream":
            continue
        values = str(row.get(key, "")).split(",")
        for value in values:
            value = value or "(none)"
            counts[value] = counts.get(value, 0) + 1
    ordered = sorted(counts.items(), key=lambda item: (-item[1], item[0]))[:limit]
    return [{key: value, "form_count": count} for value, count in ordered]


def write_tsv(path: Path, rows: list[dict[str, Any]], fields: list[str]) -> None:
    with path.open("w", encoding="utf-8", newline="") as stream:
        writer = csv.DictWriter(
            stream,
            fieldnames=fields,
            dialect="excel-tab",
            extrasaction="ignore",
            lineterminator="\n",
        )
        writer.writeheader()
        writer.writerows(rows)


def read_tsv_rows(path: Path) -> list[dict[str, str]]:
    """Read an optional generated evidence artifact without altering it."""
    with path.open("r", encoding="utf-8", newline="") as stream:
        return list(csv.DictReader(stream, delimiter="\t"))


def source_record(path: Path, base: Path) -> dict[str, Any]:
    try:
        name = path.relative_to(base).as_posix()
    except ValueError:
        name = str(path)
    return {"path": name, "sha256": sha256_file(path), "bytes": path.stat().st_size}


